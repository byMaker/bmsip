//! MODULE_CONTRACT: RFC 4733 `telephone-event` RTP DTMF codec, sender packet sequencer, and deduplicating detector.
//! INVARIANTS: 4-byte wire payload (`event`, `E|R|volume`, `duration`); sender emits marker on first packet and 3 end-of-event packets sharing one event RTP timestamp; detector deduplicates by event RTP timestamp.
//! RFC_REFS: RFC 4733 Sections 2.3, 2.5.1.4.

use std::collections::VecDeque;

use crate::error::MediaError;

/// Standard DTMF telephone-event symbols (RFC 4733 Section 3.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DtmfDigit {
    D0,
    D1,
    D2,
    D3,
    D4,
    D5,
    D6,
    D7,
    D8,
    D9,
    Star,
    Pound,
    A,
    B,
    C,
    D,
}

impl DtmfDigit {
    /// Parses an RFC 4733 numeric event code (`0..=15`).
    pub fn from_code(code: u8) -> Result<Self, MediaError> {
        match code {
            0 => Ok(Self::D0),
            1 => Ok(Self::D1),
            2 => Ok(Self::D2),
            3 => Ok(Self::D3),
            4 => Ok(Self::D4),
            5 => Ok(Self::D5),
            6 => Ok(Self::D6),
            7 => Ok(Self::D7),
            8 => Ok(Self::D8),
            9 => Ok(Self::D9),
            10 => Ok(Self::Star),
            11 => Ok(Self::Pound),
            12 => Ok(Self::A),
            13 => Ok(Self::B),
            14 => Ok(Self::C),
            15 => Ok(Self::D),
            _ => Err(MediaError::InvalidDtmf(format!(
                "unsupported DTMF event code {code}"
            ))),
        }
    }

    /// Returns the RFC 4733 numeric event code (`0..=15`).
    pub fn to_code(self) -> u8 {
        match self {
            Self::D0 => 0,
            Self::D1 => 1,
            Self::D2 => 2,
            Self::D3 => 3,
            Self::D4 => 4,
            Self::D5 => 5,
            Self::D6 => 6,
            Self::D7 => 7,
            Self::D8 => 8,
            Self::D9 => 9,
            Self::Star => 10,
            Self::Pound => 11,
            Self::A => 12,
            Self::B => 13,
            Self::C => 14,
            Self::D => 15,
        }
    }

    /// Parses a character (`'0'..'9'`, `'*'`, `'#'`, `'A'..'D'`).
    pub fn from_char(ch: char) -> Result<Self, MediaError> {
        match ch.to_ascii_uppercase() {
            '0' => Ok(Self::D0),
            '1' => Ok(Self::D1),
            '2' => Ok(Self::D2),
            '3' => Ok(Self::D3),
            '4' => Ok(Self::D4),
            '5' => Ok(Self::D5),
            '6' => Ok(Self::D6),
            '7' => Ok(Self::D7),
            '8' => Ok(Self::D8),
            '9' => Ok(Self::D9),
            '*' => Ok(Self::Star),
            '#' => Ok(Self::Pound),
            'A' => Ok(Self::A),
            'B' => Ok(Self::B),
            'C' => Ok(Self::C),
            'D' => Ok(Self::D),
            _ => Err(MediaError::InvalidDtmf(format!("invalid DTMF char '{ch}'"))),
        }
    }

    /// Formats the digit as a single character (`'0'..='9'`, `'*'`, `'#'`, `'A'..='D'`).
    pub fn to_char(self) -> char {
        match self {
            Self::D0 => '0',
            Self::D1 => '1',
            Self::D2 => '2',
            Self::D3 => '3',
            Self::D4 => '4',
            Self::D5 => '5',
            Self::D6 => '6',
            Self::D7 => '7',
            Self::D8 => '8',
            Self::D9 => '9',
            Self::Star => '*',
            Self::Pound => '#',
            Self::A => 'A',
            Self::B => 'B',
            Self::C => 'C',
            Self::D => 'D',
        }
    }
}

/// 4-byte RFC 4733 RTP payload for `telephone-event`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DtmfEventPayload {
    pub digit: DtmfDigit,
    pub end_of_event: bool,
    pub volume: u8,
    pub duration: u16,
}

impl DtmfEventPayload {
    /// Parses a 4-byte RFC 4733 event payload.
    pub fn parse(raw: &[u8]) -> Result<Self, MediaError> {
        if raw.len() < 4 {
            return Err(MediaError::InvalidDtmf(
                "DTMF payload shorter than 4 bytes".to_string(),
            ));
        }
        let digit = DtmfDigit::from_code(raw[0])?;
        let end_of_event = (raw[1] & 0x80) != 0;
        let volume = raw[1] & 0x3f;
        let duration = u16::from_be_bytes([raw[2], raw[3]]);
        Ok(Self {
            digit,
            end_of_event,
            volume,
            duration,
        })
    }

    /// Encodes the event into 4 wire bytes.
    pub fn to_bytes(self) -> Vec<u8> {
        let b1 = (u8::from(self.end_of_event) << 7) | (self.volume & 0x3f);
        let dur = self.duration.to_be_bytes();
        vec![self.digit.to_code(), b1, dur[0], dur[1]]
    }
}

/// Outbound RFC 4733 packet spec generated by [`DtmfSender`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct QueuedDtmfPacket {
    pub marker: bool,
    pub timestamp: u32,
    pub payload: DtmfEventPayload,
}

/// Generates RFC 4733 start, continuation, and 3x end-of-event packets for queued DTMF digits.
#[derive(Debug, Default)]
pub struct DtmfSender {
    queue: VecDeque<QueuedDtmfPacket>,
}

impl DtmfSender {
    /// Creates an empty [`DtmfSender`].
    pub fn new() -> Self {
        Self::default()
    }

    /// Enqueues a 100 ms DTMF tone starting at `event_timestamp` at the default 8 kHz RTP clock rate.
    pub fn queue_digit(&mut self, digit: DtmfDigit, event_timestamp: u32) {
        self.queue_digit_with_clock_rate(digit, event_timestamp, 8_000);
    }

    /// Enqueues a 100 ms DTMF tone starting at `event_timestamp`, scaling RFC 4733 duration ticks by `clock_rate_hz`.
    ///
    /// At `8000` Hz each 20 ms step is `160` ticks (`800` total); at `48000` Hz each 20 ms step is `960` ticks (`4800` total).
    pub fn queue_digit_with_clock_rate(
        &mut self,
        digit: DtmfDigit,
        event_timestamp: u32,
        clock_rate_hz: u32,
    ) {
        let volume = 10;
        let step_ticks = (clock_rate_hz.max(8_000) / 50).clamp(1, u32::from(u16::MAX) / 5) as u16;
        let total_ticks = step_ticks.saturating_mul(5);
        for step in 1..=4u16 {
            self.queue.push_back(QueuedDtmfPacket {
                marker: step == 1,
                timestamp: event_timestamp,
                payload: DtmfEventPayload {
                    digit,
                    end_of_event: false,
                    volume,
                    duration: step.saturating_mul(step_ticks),
                },
            });
        }
        // RFC 4733 §2.5.1.4 recommends retransmitting the end-of-event packet 3 times.
        for _ in 0..3 {
            self.queue.push_back(QueuedDtmfPacket {
                marker: false,
                timestamp: event_timestamp,
                payload: DtmfEventPayload {
                    digit,
                    end_of_event: true,
                    volume,
                    duration: total_ticks,
                },
            });
        }
    }

    /// Pops the next queued DTMF packet spec, if any.
    pub fn pop_packet(&mut self) -> Option<QueuedDtmfPacket> {
        self.queue.pop_front()
    }
}

/// Deduplicates inbound RFC 4733 packets by RTP event timestamp.
#[derive(Debug, Default)]
pub struct DtmfDetector {
    last_event_timestamp: Option<u32>,
}

impl DtmfDetector {
    /// Creates a new [`DtmfDetector`].
    pub fn new() -> Self {
        Self::default()
    }

    /// Feeds one parsed [`DtmfEventPayload`] and its RTP timestamp, emitting `Some(digit)` once per tone.
    pub fn feed(&mut self, rtp_timestamp: u32, event: DtmfEventPayload) -> Option<DtmfDigit> {
        if self.last_event_timestamp == Some(rtp_timestamp) {
            return None;
        }
        self.last_event_timestamp = Some(rtp_timestamp);
        Some(event.digit)
    }

    /// Resets deduplication state (e.g., after a mid-call remote SSRC change).
    pub fn reset(&mut self) {
        self.last_event_timestamp = None;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dtmf_sender_and_detector_deduplicate_end_packets() {
        let mut sender = DtmfSender::new();
        sender.queue_digit(DtmfDigit::Pound, 1600);
        sender.queue_digit(DtmfDigit::D5, 3200);

        let mut detector = DtmfDetector::new();
        let mut detected = Vec::new();
        let mut count = 0;

        while let Some(pkt) = sender.pop_packet() {
            count += 1;
            let bytes = pkt.payload.to_bytes();
            let parsed = DtmfEventPayload::parse(&bytes).unwrap();
            if let Some(d) = detector.feed(pkt.timestamp, parsed) {
                detected.push(d);
            }
        }

        assert_eq!(count, 14); // 7 packets per digit (4 active + 3 E-bit repeats)
        assert_eq!(detected, vec![DtmfDigit::Pound, DtmfDigit::D5]);
    }
}
